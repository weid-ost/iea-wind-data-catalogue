// design/fonts/*.woff2 -> site/public/fonts/, and the @font-face stylesheet
// that points at them (site/src/styles/fonts.css).
//
// The fonts are committed once, in design/fonts/, because they are part of the
// design system rather than of the site; this copies them into Astro's public
// directory so there is exactly one authoritative copy in the repository.
//
// The @font-face `src` URLs are generated here rather than hand-written because
// they must carry the deployment `base` path. Astro serves `public/` under the
// site base (`/iea-wind-data-catalogue/` today, `/` on a custom domain), so a
// bare `/fonts/x.woff2` in a static stylesheet 404s under the project site.
// Astro does not rewrite absolute URLs inside CSS, so the base is baked in here
// from SITE_BASE — the same value astro.config.mjs feeds to `import.meta.env.
// BASE_URL` — keeping "switch to a custom domain" a one-env-var change (url.ts).
//
// No CDN, ever: a third-party font request is a third-party dependency, a
// privacy leak and a thing that can rot (design-system.md §3).
import { cpSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(site, '..', 'design', 'fonts');
const to = join(site, 'public', 'fonts');
const cssOut = join(site, 'src', 'styles', 'fonts.css');

mkdirSync(to, { recursive: true });
const files = readdirSync(from).filter((f) => f.endsWith('.woff2'));
if (files.length === 0) throw new Error(`no woff2 files in ${from} — the Plex subsets are missing`);
for (const file of files) cpSync(join(from, file), join(to, file));

// The `base` path, exactly as Astro resolves it (astro.config.mjs default,
// stripped of any trailing slash). Empty string on a custom domain (SITE_BASE=/).
const base = (process.env.SITE_BASE ?? '/iea-wind-data-catalogue').replace(/\/+$/, '');
const url = (file) => `${base}/fonts/${file}`;

// The two subset ranges the Plex woff2 files were built to. Kept as data so the
// generated stylesheet stays byte-for-byte deterministic.
const LATIN =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC,\n' +
  '    U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215,\n' +
  '    U+FEFF, U+FFFD';
const LATIN_EXT =
  'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304,\n' +
  '    U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0,\n' +
  '    U+2113, U+2C60-2C7F, U+A720-A7FF';

const FACES = [
  ['IBM Plex Sans', 400, 'ibm-plex-sans-latin-400-normal.woff2', LATIN],
  ['IBM Plex Sans', 400, 'ibm-plex-sans-latin-ext-400-normal.woff2', LATIN_EXT],
  ['IBM Plex Sans', 500, 'ibm-plex-sans-latin-500-normal.woff2', LATIN],
  ['IBM Plex Sans', 500, 'ibm-plex-sans-latin-ext-500-normal.woff2', LATIN_EXT],
  ['IBM Plex Sans', 600, 'ibm-plex-sans-latin-600-normal.woff2', LATIN],
  ['IBM Plex Sans', 600, 'ibm-plex-sans-latin-ext-600-normal.woff2', LATIN_EXT],
  ['IBM Plex Mono', 400, 'ibm-plex-mono-latin-400-normal.woff2', LATIN],
  ['IBM Plex Mono', 400, 'ibm-plex-mono-latin-ext-400-normal.woff2', LATIN_EXT],
];

// Fail loudly if the table and the shipped binaries drift apart.
for (const [, , file] of FACES) {
  if (!files.includes(file)) throw new Error(`fonts.css table names ${file}, missing from design/fonts/`);
}

const face = ([family, weight, file, range]) => `@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('${url(file)}') format('woff2');
  unicode-range: ${range};
}`;

const css = `/* GENERATED by scripts/sync-fonts.mjs. Never hand-edit — change the font set
   in design/fonts/ (and the FACES table in sync-fonts.mjs) and re-run
   \`npm run tokens\`. IBM Plex Sans + IBM Plex Mono, self-hosted subset woff2
   (design-system.md §3). The binaries live in design/fonts/ and are copied to
   public/fonts/; the \`src\` URLs carry the deployment base path so they resolve
   under the project site as well as a custom domain. No CDN, ever.

   This file is allow-listed by scripts/check-tokens.mjs for its @font-face
   paths only — do not put anything else in it. */

${FACES.map(face).join('\n')}
`;

writeFileSync(cssOut, css);
console.log(`sync-fonts: ${files.length} woff2 -> site/public/fonts/, ${FACES.length} @font-face -> src/styles/fonts.css (base "${base || '/'}")`);
